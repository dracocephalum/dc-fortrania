using Dracocephalum.Fortrania.Emit;
using Dracocephalum.Fortrania.Runtime;
using Shouldly;

namespace Dracocephalum.Fortrania.Tests.Emit;

public class CSharpEmitterTests
{
    [Fact]
    public void Emit_WhenUnitIsASubroutine_ShouldWriteAMethodOfThePartialClass()
    {
        // Act
        var file = TranslatedProgram.Translate(
            """
                  SUBROUTINE VSCL ( S, V1, VOUT )
                  IMPLICIT NONE
                  INTEGER SIZE, I
                  PARAMETER ( SIZE = 3 )
                  DOUBLE PRECISION S, V1 ( SIZE ), VOUT ( SIZE )
                  DO I = 1, SIZE
                     VOUT ( I ) = S * V1 ( I )
                  END DO
                  VOUT ( 2 ) = -VOUT ( 2 )
                  RETURN
                  END
            """).ShouldHaveSingleItem();

        // Assert
        file.ShouldBe(
            """
            // <auto-generated>
            // Translated from FORTRAN 77 by Fortrania. A change made here is lost when the source is translated again.
            // </auto-generated>

            #nullable enable

            using System;
            using Dracocephalum.Fortrania.Runtime;

            namespace Translated;

            public unsafe partial class Library
            {
                public void VSCL(double* s, double* v1, double* vout)
                {
                    const int size = 3;
                    int i = 0;
                    for (i = 1; i <= size; i += 1)
                    {
                        vout[i - 1] = *s * v1[i - 1];
                    }
                    vout[1] = -vout[1];
                    return;
                }
            }

            """,
            StringCompareShould.IgnoreLineEndings);
    }

    [Fact]
    public void Emit_WhenNamesAreKeywordsOfCSharp_ShouldEscapeThem()
    {
        // Arrange
        var program = TranslatedProgram.Compile(
            """
                  INTEGER FUNCTION DOUBLE ( IN, OUT, REF )
                  INTEGER IN, OUT, REF, INT, BASE ( 2 )
                  INT = IN + 1
                  BASE ( 2 ) = INT * 2
                  OUT = BASE ( 2 )
                  DOUBLE = OUT + REF
                  END
            """,
            """
                public static int[] Run()
                {
                    int a = 4, b = 0, c = 100;
                    var result = new Library().DOUBLE(&a, &b, &c);
                    return [result, b];
                }
            """);

        // Act & Assert
        program.Run<int[]>("Run").ShouldBe([110, 10]);
    }

    [Fact]
    public void Emit_WhenStopIsReached_ShouldThrowWithItsCode()
    {
        // Arrange
        var program = TranslatedProgram.Compile(
            """
                  SUBROUTINE HALT ( N )
                  INTEGER N
                  IF ( N .GT. 0 ) STOP 7
                  STOP
                  END
            """,
            """
                public static int Run(int n)
                {
                    new Library().HALT(&n);
                    return 0;
                }

                public static int RunWithOne() => Run(1);

                public static int RunWithZero() => Run(0);
            """);

        // Act & Assert
        Should.Throw<FortranStopException>(() => program.Run<int>("RunWithOne")).ExitCode.ShouldBe(7);
        Should.Throw<FortranStopException>(() => program.Run<int>("RunWithZero")).ExitCode.ShouldBe(0);
    }

    [Fact]
    public void Emit_WhenArgumentIsOfAnotherTypeThanTheProcedureDeclares_ShouldPassTheSameStorage()
    {
        // Arrange: a double precision array is handed to a routine that
        // moves integers, twice as many, which is how one program of the
        // reference sources copies such arrays.
        var program = TranslatedProgram.Compile(
            """
                  SUBROUTINE MOVEI ( FROM, N, TO )
                  INTEGER N, FROM ( N ), TO ( N ), I
                  DO I = 1, N
                     TO ( I ) = FROM ( I )
                  END DO
                  END
                  SUBROUTINE MOVED ( FROM, N, TO )
                  INTEGER N
                  DOUBLE PRECISION FROM ( N ), TO ( N )
                  CALL MOVEI ( FROM, 2 * N, TO )
                  END
                  SUBROUTINE SETD ( X )
                  DOUBLE PRECISION X
                  X = 5
                  END
                  DOUBLE PRECISION FUNCTION WIDEN ( A )
                  DOUBLE PRECISION A ( 3 ), B ( 3 )
                  CALL MOVED ( A, 3, B )
                  CALL SETD ( 0.0 )
                  CALL MOVED ( B ( 2 ), 1, B ( 1 ) )
                  WIDEN = B ( 1 ) * 100 + B ( 2 ) * 10 + B ( 3 )
                  END
            """,
            """
                public static double Run()
                {
                    double* a = stackalloc double[3];
                    a[0] = 1.5;
                    a[1] = 2.5;
                    a[2] = 3.5;
                    return new Library().WIDEN(a);
                }
            """);

        // Act & Assert
        program.Run<double>("Run").ShouldBe(278.5);
    }

    [Theory]
    [InlineData("      PROGRAM MAIN|      END", "Line 1: a main program cannot be translated yet.")]
    [InlineData("      BLOCK DATA|      END", "Line 1: a block data subprogram cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      RETURN|      ENTRY T|      END", "Line 1: ENTRY cannot be translated yet.")]
    [InlineData("      SUBROUTINE S ( X )|      SF ( Y ) = Y + 1|      X = SF ( X )|      END", "Line 1: a statement function cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      INTEGER I, J|      EQUIVALENCE ( I, J )|      END", "Line 1: EQUIVALENCE cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      INTEGER I|      DATA I / 1 /|      END", "Line 1: DATA cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      SAVE|      END", "Line 1: SAVE cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      INTEGER I|      SAVE I|      END", "Line 2: SAVE cannot be translated yet.")]
    [InlineData("      SUBROUTINE S ( F )|      EXTERNAL F|      CALL F|      END", "Line 1: a procedure as an argument cannot be translated yet.")]
    [InlineData("      SUBROUTINE S ( C )|      CHARACTER*(*) C|      END", "Line 1: a CHARACTER variable cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      COMPLEX Z|      Z = 1|      END", "Line 2: a COMPLEX variable cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      CALL T ( 'A' )|      END", "Line 2: a character constant cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      DOUBLE PRECISION A ( 513 )|      A ( 1 ) = 0|      END", "Line 2: a local array of more than 4096 bytes cannot be translated yet.")]
    [InlineData("      SUBROUTINE S ( X )|      WRITE ( *, * ) X|      END", "Line 2: an input or output statement cannot be translated yet.")]
    [InlineData("      SUBROUTINE S ( I )|      I = ISHFT ( I, 2 )|      END", "Line 2: the intrinsic function ISHFT cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      INTRINSIC SIN|      CALL T ( SIN )|      END", "Line 3: a procedure as an argument cannot be translated yet.")]
    [InlineData("      SUBROUTINE S|      STOP 'DONE'|      END", "Line 2: STOP with a character constant cannot be translated yet.")]
    public void Emit_WhenUnitUsesWhatIsNotTranslatedYet_ShouldSayWhatAndWhere(string source, string message)
    {
        // Act & Assert
        var exception = Should.Throw<UnsupportedConstructException>(
            () => TranslatedProgram.Translate(source.Replace('|', '\n')));
        exception.Message.ShouldBe(message);
    }
}
