using Dracocephalum.Fortrania.Emit;
using Dracocephalum.Fortrania.Runtime;
using Shouldly;

namespace Dracocephalum.Fortrania.Tests.Emit;

public class CSharpEmitterTests
{
    [Fact]
    public void Emit_WhenUnitIsASubroutine_ShouldWriteAMethodOfThePartialClass()
    {
        // Act
        var file = TranslatedProgram.Translate(
            """
                  SUBROUTINE VSCL ( S, V1, VOUT )
                  IMPLICIT NONE
                  INTEGER SIZE, I
                  PARAMETER ( SIZE = 3 )
                  DOUBLE PRECISION S, V1 ( SIZE ), VOUT ( SIZE )
                  DO I = 1, SIZE
                     VOUT ( I ) = S * V1 ( I )
                  END DO
                  VOUT ( 2 ) = -VOUT ( 2 )
                  RETURN
                  END
            """).ShouldHaveSingleItem();

        // Assert
        file.ShouldBe(
            """
            // <auto-generated>
            // Translated from FORTRAN 77 by Fortrania. A change made here is lost when the source is translated again.
            // </auto-generated>

            #nullable enable
            #pragma warning disable CS0162, CS0219, CS1717

            using System;
            using System.Runtime.CompilerServices;
            using Dracocephalum.Fortrania.Runtime;
            using static Dracocephalum.Fortrania.Runtime.Fortran;

            namespace Translated;

            public unsafe partial class Library
            {
                public void VSCL(double* s, double* v1, double* vout)
                {
                    const int size = 3;
                    int i = 0;
                    for (i = 1; i <= size; i += 1)
                    {
                        vout[i - 1] = *s * v1[i - 1];
                    }
                    vout[1] = -vout[1];
                    return;
                }
            }

            """,
            StringCompareShould.IgnoreLineEndings);
    }

    [Fact]
    public void Emit_WhenUnitHandlesCharacterData_ShouldWriteAddressesWithLengthsBesideThem()
    {
        // Act
        var file = TranslatedProgram.Translate(
            """
                  LOGICAL FUNCTION SAME ( NAME, LIST, N )
                  IMPLICIT NONE
                  INTEGER N, I
                  CHARACTER*(*) NAME, LIST ( N )
                  CHARACTER*8 KEY
                  KEY = NAME ( 2: )
                  SAME = .FALSE.
                  DO I = 1, N
                     IF ( LIST ( I ) .EQ. KEY ) SAME = .TRUE.
                  END DO
                  CALL CHKIN ( 'SAME' )
                  END
            """).ShouldHaveSingleItem();

        // Assert
        file.ShouldContain(
            """
                public bool SAME(byte* name, int name_len, byte* list, int list_len, int* n)
                {
                    int same = 0;
                    int i = 0;
                    byte* key = stackalloc byte[8];
                    Assign(key, 8, name + 1, name_len - 1);
                    same = 0;
                    int _last1 = *n;
                    for (i = 1; i <= _last1; i += 1)
                    {
                        if (Compare(list + (i - 1) * list_len, list_len, key, 8) == 0)
                        {
                            same = 1;
                        }
                    }
                    CHKIN(AddrOf("SAME"u8), 4);
                    return same != 0;
                }
            """.ReplaceLineEndings("\n"),
            Case.Sensitive);
    }

    [Fact]
    public void Emit_WhenNamesAreKeywordsOfCSharp_ShouldEscapeThem()
    {
        // Arrange
        var program = TranslatedProgram.Compile(
            """
                  INTEGER FUNCTION DOUBLE ( IN, OUT, REF )
                  INTEGER IN, OUT, REF, INT, BASE ( 2 )
                  INT = IN + 1
                  BASE ( 2 ) = INT * 2
                  OUT = BASE ( 2 )
                  DOUBLE = OUT + REF
                  END
            """,
            """
                public static int[] Run()
                {
                    int a = 4, b = 0, c = 100;
                    var result = new Standalone().DOUBLE(&a, &b, &c);
                    return [result, b];
                }
            """);

        // Act & Assert
        program.Run<int[]>("Run").ShouldBe([110, 10]);
    }

    [Fact]
    public void Emit_WhenALogicalValueIsPassed_ShouldPassItAsTheIntegerItIsStoredAs()
    {
        // Arrange
        var program = TranslatedProgram.Compile(
            """
                  INTEGER FUNCTION TALLY ( A, B, C )
                  LOGICAL A, B, C
                  TALLY = 0
                  IF ( A ) TALLY = TALLY + 1
                  IF ( B ) TALLY = TALLY + 10
                  IF ( C ) TALLY = TALLY + 100
                  END
                  INTEGER FUNCTION PASS ( N )
                  INTEGER N, TALLY
                  LOGICAL YES
                  PARAMETER ( YES = .TRUE. )
                  PASS = TALLY ( .TRUE., N .GT. 5, .FALSE. )
                 .     + 1000 * TALLY ( .NOT. YES, YES, N .LT. 5 .OR. YES )
                  END
            """,
            """
                public static int Run()
                {
                    int seven = 7;
                    return new Standalone().PASS(&seven);
                }
            """);

        // Act & Assert
        program.Run<int>("Run").ShouldBe(110011);
    }

    [Fact]
    public void Emit_WhenTheCodeOfACharacterIsAnArgumentOfAGenericFunction_ShouldPassItAsAnInteger()
    {
        // Arrange
        var program = TranslatedProgram.Compile(
            """
                  INTEGER FUNCTION CAPPED ( C )
                  CHARACTER*(*) C
                  CAPPED = MIN ( 100, ICHAR ( C ( 2:2 ) ) )
                 .       + MAX ( ICHAR ( C ( 1:1 ) ), 70 )
                  END
            """,
            """
                public static int Run()
                {
                    fixed (byte* text = "Az"u8)
