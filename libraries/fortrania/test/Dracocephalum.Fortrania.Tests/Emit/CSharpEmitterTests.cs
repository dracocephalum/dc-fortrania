    [Fact]
    public void EmitClass_WhenWritten_ShouldMakeAnInstanceOverTheContextOfItsProgram()
    {
        // Act
        var file = new CSharpEmitter(new EmitOptions("N", "C"), _ => null).EmitClass();

        // Assert
        file.ShouldContain(
            """
            public unsafe partial class C : IFortranLibrary<C>
            {
                private readonly FortranContext _context;
                private readonly StateMemory _memory;
                private readonly FortranIO _io;

            """.ReplaceLineEndings("\n"),
            Case.Sensitive);
        file.ShouldContain(
            """
                public C(FortranContext context)
                {
                    ArgumentNullException.ThrowIfNull(context);
                    _context = context;
                    _memory = context.Memory;
                    _io = context.IO;
                    context.Add(this);
                }

                /// <summary>Gets the context of the program this library is part of.</summary>
                public FortranContext Context => _context;

                /// <inheritdoc/>
                static C IFortranLibrary<C>.Create(FortranContext context) => new(context);
            }
            """.ReplaceLineEndings("\n"),
            Case.Sensitive);
    }

    [Fact]
    public void Emit_WhenStopIsReached_ShouldThrowWithItsCode()
    {
        // Arrange
        var program = TranslatedProgram.Compile(
            """
                  SUBROUTINE HALT ( N )
                  INTEGER N
                  IF ( N .GT. 0 ) STOP 7
                  STOP
                  END
            """,
            """
                public static int Run(int n)
                {
                    new Standalone().HALT(&n);
                    return 0;
                }

                public static int RunWithOne() => Run(1);

                public static int RunWithZero() => Run(0);
            """);

        // Act & Assert
        Should.Throw<FortranStopException>(() => program.Run<int>("RunWithOne")).ExitCode.ShouldBe(7);
        Should.Throw<FortranStopException>(() => program.Run<int>("RunWithZero")).ExitCode.ShouldBe(0);
    }

    [Fact]
    public void Emit_WhenArgumentIsOfAnotherTypeThanTheProcedureDeclares_ShouldPassTheSameStorage()
    {
        // Arrange: a double precision array is handed to a routine that
        // moves integers, twice as many, which is how one program of the
        // reference sources copies such arrays.
        var program = TranslatedProgram.Compile(
            """
                  SUBROUTINE MOVEI ( FROM, N, TO )
                  INTEGER N, FROM ( N ), TO ( N ), I
                  DO I = 1, N
                     TO ( I ) = FROM ( I )
                  END DO
                  END
                  SUBROUTINE MOVED ( FROM, N, TO )
                  INTEGER N
                  DOUBLE PRECISION FROM ( N ), TO ( N )
                  CALL MOVEI ( FROM, 2 * N, TO )
                  END
                  SUBROUTINE SETD ( X )
                  DOUBLE PRECISION X
                  X = 5
                  END
                  DOUBLE PRECISION FUNCTION WIDEN ( A )
                  DOUBLE PRECISION A ( 3 ), B ( 3 )
                  CALL MOVED ( A, 3, B )
                  CALL SETD ( 0.0 )
                  CALL MOVED ( B ( 2 ), 1, B ( 1 ) )
                  WIDEN = B ( 1 ) * 100 + B ( 2 ) * 10 + B ( 3 )
                  END
            """,
            """
                public static double Run()
                {
                    double* a = stackalloc double[3];
                    a[0] = 1.5;
                    a[1] = 2.5;
                    a[2] = 3.5;
                    return new Standalone().WIDEN(a);
                }
            """);

        // Act & Assert
        program.Run<double>("Run").ShouldBe(278.5);
    }

