using Dracocephalum.Fortrania.Emit;
using Shouldly;

namespace Dracocephalum.Fortrania.Tests.Emit;

public class CSharpFileWriterTests
{
    private static readonly TreeExpression I = new TreeExpression.Local("i");
    private static readonly TreeExpression N = new TreeExpression.Local("n");

    [Fact]
    public void Write_WhenGivenAFile_ShouldWriteItsHeadingAndItsMembersABlankLineApart()
    {
        // Arrange
        var state = new TreeExpression.Local("_state");
        var loader = new TreeMethod([], "byte*", "_load_FIRST", [], [], [], [new TreeStatement.Return(state)])
        {
            IsPublic = false,
            IsKeptOutOfLine = true,
        };
        var forwarder = new TreeMethod(
            [],
            "void",
            "_FIRST_passes_SECOND",
            ["FortranContext context"],
            [],
            [],
            [new TreeStatement.Evaluate(new TreeExpression.MemberCall(new TreeExpression.Call("context.Get<Library>", []), "SECOND", []))])
        {
            IsPublic = false,
            IsStatic = true,
            IsOneExpression = true,
        };
        var first = new TreeMethod(
            [new TreeStatement.Comment("About the first.")],
            "void",
            "FIRST",
            ["int* n"],
            [new TreeStatement.Comment("Among its declarations.")],
            [new TreeStatement.Declare("int", "i", new TreeExpression.Integer(0))],
            [new TreeStatement.Comment("Before its code."), new TreeStatement.Assign(I, N)]);
        var second = new TreeMethod([], "int", "SECOND", [], [], [], [new TreeStatement.Comment("All it has."), new TreeStatement.Return(I)]);
        var file = new TreeFile(
            "FIRST",
            "first.f",
            "Translated",
            "Library",
            "Dracocephalum.Fortrania.Runtime.Fortran",
            null,
            ["CS0162", "CS0219"],
            [new TreeField("byte*", "_state_FIRST"), loader, forwarder, first, second],
            [new TreeStatement.Comment("After the end.")]);

        // Act
        var text = CSharpFileWriter.Write(file);

        // Assert
        text.ShouldBe(
            """
            // <auto-generated>
            // Translated from FORTRAN 77 by Fortrania: FIRST, from first.f.
            // A change made here is lost when the source is translated again.
            // </auto-generated>

            #nullable enable
            #pragma warning disable CS0162, CS0219

            using System;
            using System.Runtime.CompilerServices;
            using Dracocephalum.Fortrania.Runtime;
            using static Dracocephalum.Fortrania.Runtime.Fortran;

            namespace Translated;

            public unsafe partial class Library
            {
                private byte* _state_FIRST;

                [MethodImpl(MethodImplOptions.NoInlining)]
                private byte* _load_FIRST()
                {
                    return _state;
                }

                private static void _FIRST_passes_SECOND(FortranContext context) => context.Get<Library>().SECOND();

                // About the first.
                public void FIRST(int* n)
                {
                    // Among its declarations.

                    int i = 0;

                    // Before its code.
                    i = n;
                }

                public int SECOND()
                {
                    // All it has.
                    return i;
                }

                // After the end.
            }

            """,
            StringCompareShould.IgnoreLineEndings);
    }

    [Fact]
    public void Write_WhenTheRuntimeHasAnAliasAndTheSourceNoName_ShouldSaySoInTheHeading()
    {
        // Arrange
        var file = new TreeFile("MAIN", null, "N", "C", "Dracocephalum.Fortrania.Runtime.Fortran", "F77", ["CS0162"], [], []);

        // Act
        var text = CSharpFileWriter.Write(file);

        // Assert
        text.ShouldContain("// Translated from FORTRAN 77 by Fortrania: MAIN.\n");
        text.ShouldContain("using F77 = Dracocephalum.Fortrania.Runtime.Fortran;\n");
        text.ShouldNotContain("using static");
    }
}
