namespace Dracocephalum.Fortrania.Emit;

/// <summary>
/// Writes a file of the program tree as C# source. It chooses spelling
/// and layout and nothing else.
/// </summary>
internal static class CSharpFileWriter
{
    /// <summary>Writes a file.</summary>
    /// <returns>The text of the C# source file.</returns>
    public static string Write(TreeFile file)
    {
        var text = new CodeWriter();
        text.Line("// <auto-generated>");
        text.Line(file.SourceFile is null
            ? $"// Translated from FORTRAN 77 by Fortrania: {file.UnitName}."
            : $"// Translated from FORTRAN 77 by Fortrania: {file.UnitName}, from {file.SourceFile}.");
        text.Line("// A change made here is lost when the source is translated again.");
        text.Line("// </auto-generated>");
        text.Blank();
        text.Line("#nullable enable");
        text.Line($"#pragma warning disable {string.Join(", ", file.SuppressedWarnings)}");
        text.Blank();
        text.Line("using System;");
        text.Line("using System.Runtime.CompilerServices;");
        text.Line("using Dracocephalum.Fortrania.Runtime;");
        text.Line(file.RuntimeAlias is null
            ? $"using static {file.RuntimeClass};"
            : $"using {file.RuntimeAlias} = {file.RuntimeClass};");
        text.Blank();
        text.Line($"namespace {file.Namespace};");
        text.Blank();
        text.Open($"public unsafe partial class {file.ClassName}");

        // Members are a blank line apart.
        for (var index = 0; index < file.Members.Count; index++)
        {
            if (index > 0)
            {
                text.Blank();
            }

            Write(text, file.Members[index]);
        }

        if (file.TrailingComments.Count > 0)
        {
            text.Blank();
            CSharpStatementWriter.Write(text, file.TrailingComments);
        }

        text.Close();
        return text.ToString();
    }

    private static void Write(CodeWriter text, TreeMember member)
    {
        switch (member)
        {
            case TreeField field:
                text.Line($"private {field.Type} {field.Name};");
                break;

            case TreeMethod method:
                Write(text, method);
                break;

            default:
                throw new ArgumentOutOfRangeException(nameof(member));
        }
    }

    private static void Write(CodeWriter text, TreeMethod method)
    {
        CSharpStatementWriter.Write(text, method.Comments);
        if (method.IsKeptOutOfLine)
        {
            text.Line("[MethodImpl(MethodImplOptions.NoInlining)]");
        }
        else if (method.IsInlined)
        {
            text.Line("[MethodImpl(MethodImplOptions.AggressiveInlining)]");
        }

        var access = method.IsPublic ? "public" : method.IsInternal ? "internal" : "private";
        var heading = $"{access} {(method.IsStatic ? "static " : string.Empty)}"
            + $"{method.ReturnType} {method.Name}({string.Join(", ", method.Parameters)})";
        if (method.IsOneExpression)
        {
            var expression = method.Body[0] switch
            {
                TreeStatement.Evaluate evaluated => evaluated.Expression,
                TreeStatement.Return { Value: { } value } => value,
                _ => throw new ArgumentOutOfRangeException(nameof(method)),
            };
            text.Line($"{heading} => {CSharpExpressionWriter.Write(expression)};");
            return;
        }

        text.Open(heading);
        if (method.Preamble.Count > 0)
        {
            CSharpStatementWriter.Write(text, method.Preamble);
            text.Blank();
        }

        // Comments that open the code are a block of their own after what is
        // declared, as anywhere else after code.
        CSharpStatementWriter.Write(text, method.Declarations);
        if (method.Declarations.Count > 0 && method.Body is [TreeStatement.Comment, ..])
        {
            text.Blank();
        }

        CSharpStatementWriter.Write(text, method.Body);
        text.Close();
    }
}
