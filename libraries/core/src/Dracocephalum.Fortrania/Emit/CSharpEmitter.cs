using Dracocephalum.Fortrania.Analysis;

namespace Dracocephalum.Fortrania.Emit;

/// <summary>
/// Writes an analysed program unit as C# source: one file that adds the
/// unit's procedures to the class the options name.
/// </summary>
public sealed class CSharpEmitter
{
    /// <summary>The name of the method a main program becomes when the source gives it none.</summary>
    public const string MainProgramName = "MAIN";

    private readonly EmitOptions _options;
    private readonly Func<string, ProcedureInterface?> _findProcedure;

    /// <summary>Initializes a new instance of the <see cref="CSharpEmitter"/> class.</summary>
    /// <param name="options">What the emitted code is to be called.</param>
    /// <param name="findProcedure">
    /// Gives the procedure of this library a name is called by, or
    /// <see langword="null"/> when it defines none of that name; the
    /// libraries the options refer to are asked after it. A call is written to suit the
    /// procedure it reaches where that is known, and by its own arguments
    /// alone where it is not.
    /// </param>
    public CSharpEmitter(EmitOptions options, Func<string, ProcedureInterface?> findProcedure)
    {
        ArgumentNullException.ThrowIfNull(options);
        ArgumentNullException.ThrowIfNull(findProcedure);

        _options = options;
        _findProcedure = findProcedure;
    }

    /// <summary>
    /// Tells whether a name is one of the procedures a program takes from
    /// its compiler's library, which the program's context supplies where
    /// the program defines none of that name.
    /// </summary>
    /// <param name="name">A procedure's name, in upper case.</param>
    /// <returns>Whether the context supplies it.</returns>
    public static bool IsSuppliedByContext(string name) => UnitEmitter.SystemProcedures.ContainsKey(name);

    /// <summary>
    /// Writes the part of the class that belongs to no program unit: how
    /// an instance is made over the context of its program, which holds
    /// what the program's libraries share. The class is complete with this
    /// file and one per program unit.
    /// </summary>
    /// <param name="region">
    /// What the library is to ask of its context for its project's working
    /// buffers, where its units were written to keep them wherever the
    /// context says; nothing where they keep them on the stack.
    /// </param>
    /// <returns>The text of a C# source file.</returns>
    public string EmitClass(LibraryRegion? region = null)
    {
        var name = _options.ClassName;
        var file = new CodeWriter();
        file.Line("// <auto-generated>");
        file.Line("// Written by Fortrania with the code it translated from FORTRAN 77. A change made here is lost when the source is translated again.");
        file.Line("// </auto-generated>");
        file.Blank();
        file.Line("#nullable enable");
        file.Blank();
        file.Line("using System;");
        file.Line("using System.Runtime.CompilerServices;");
        file.Line("using Dracocephalum.Fortrania.Runtime;");
        file.Blank();
        file.Line($"namespace {_options.Namespace};");
        file.Blank();
        file.Line("/// <summary>");
        file.Line("/// Code translated from FORTRAN 77. An instance is the library as one program has it:");
        file.Line("/// what the FORTRAN keeps between calls is kept per instance, in the memory of the");
        file.Line("/// program's context, and its files and units are the context's.");
        file.Line("/// </summary>");

        // FORTRAN gives a local no value until the program does, so nothing
        // here asks for one: without this, every method clears what it takes
        // from the stack on each call. On the class, it holds for every
        // method of every file of it.
        file.Line("[SkipLocalsInit]");
        file.Open($"public unsafe partial class {name} : IFortranLibrary<{name}>");
        file.Line("private readonly FortranContext _context;");
        file.Line("private readonly StateMemory _memory;");
        file.Line("private readonly FortranIO _io;");
        if (region is not null)
        {
            file.Line($"private readonly BufferRegion {WorkingBuffersPass.RegionField};");
        }

        // Another library of the program is asked of the context when it
        // is first called, which makes it if nothing has, and not when
        // this one is made, so that the libraries of a program need no
        // order and may call each other both ways.
        foreach (var reference in _options.References)
        {
            file.Line($"private {reference.QualifiedName}? _library{reference.Accessor};");
        }

        file.Blank();
        foreach (var reference in _options.References)
        {
            file.Line($"private {reference.QualifiedName} {reference.Accessor} => _library{reference.Accessor} ??= _context.Get<{reference.QualifiedName}>();");
            file.Blank();
        }

        file.Line($"/// <summary>Initializes a new instance of the <see cref=\"{name}\"/> class as part of a program.</summary>");
        file.Line("/// <param name=\"context\">What the libraries of the program share. It is disposed by whoever made it, and the instance is not to be used after that.</param>");
        file.Open($"public {name}(FortranContext context)");
        file.Line("ArgumentNullException.ThrowIfNull(context);");
        file.Line("_context = context;");
        file.Line("_memory = context.Memory;");
        file.Line("_io = context.IO;");
        if (region is not null)
        {
            // Every library of a project is given the same region, as large
            // as the most any of them made so far asked for, and the context
            // lays it out after those of the projects that call in.
            var refersTo = string.Join(", ", region.RefersTo.Select(name => $"\"{name}\""));
            file.Line(string.Create(
                System.Globalization.CultureInfo.InvariantCulture,
                $"{WorkingBuffersPass.RegionField} = context.Working.Register(\"{region.Project}\", {region.OwnBytes}, {region.ReachBytes}, [{refersTo}], WorkingBuffers.Default);"));
        }

        file.Line("context.Add(this);");
        file.Close();
        file.Blank();
        file.Line("/// <summary>Gets the context of the program this library is part of.</summary>");
        file.Line("public FortranContext Context => _context;");
        file.Blank();
        file.Line("/// <inheritdoc/>");
        file.Line($"static {name} IFortranLibrary<{name}>.Create(FortranContext context) => new(context);");
        file.Close();
        return file.ToString();
    }

    /// <summary>Writes the program unit <paramref name="table"/> describes.</summary>
    /// <param name="table">The names of a program unit that has passed the type check.</param>
    /// <param name="sourceFile">
    /// The file the unit was read from, which the header names without its
    /// folder; <see langword="null"/> when there is none.
    /// </param>
    /// <returns>The text of a C# source file.</returns>
    /// <exception cref="UnsupportedConstructException">The unit uses something the emitter cannot translate yet.</exception>
    /// <exception cref="Analysis.FortranAnalysisException">The unit lays variables out in a way the language forbids, which shows only when their places are worked out.</exception>
    public string Emit(SymbolTable table, string? sourceFile = null) => EmitUnit(table, sourceFile).Text;

    /// <summary>
    /// Writes the program unit <paramref name="table"/> describes, and tells
    /// what each of its methods takes from the stack and which of its
    /// variables lie off their alignment.
    /// </summary>
    /// <param name="table">The names of a program unit that has passed the type check.</param>
    /// <param name="sourceFile">
    /// The file the unit was read from, which the header names without its
    /// folder; <see langword="null"/> when there is none.
    /// </param>
    /// <returns>The text, and what was learnt writing it.</returns>
    /// <exception cref="UnsupportedConstructException">The unit uses something the emitter cannot translate yet.</exception>
    /// <exception cref="Analysis.FortranAnalysisException">The unit lays variables out in a way the language forbids, which shows only when their places are worked out.</exception>
    public EmittedUnit EmitUnit(SymbolTable table, string? sourceFile = null)
    {
        ArgumentNullException.ThrowIfNull(table);

        return new UnitEmitter(table, _options, _findProcedure, sourceFile).Emit();
    }

    /// <summary>
    /// Writes a unit again so that a context chooses where its procedures
    /// keep their working buffers: on the stack, or each at its place in
    /// the project's region of the context's block. The class is then to
    /// be written with the region, by <see cref="EmitClass"/>.
    /// </summary>
    /// <param name="unit">A unit as <see cref="EmitUnit"/> gave it.</param>
    /// <param name="placeOf">Where a procedure's buffers start in its project's region, by the procedure's name; nothing for one that is to keep the stack.</param>
    /// <returns>The text of a C# source file.</returns>
    /// <param name="text">
    /// The block of the unit's library, which is given the unit's character
    /// constants; the block is then to be written too, by
    /// <see cref="EmitTextBlock"/>. Nothing for a unit that is to write
    /// its constants itself.
    /// </param>
    /// <param name="keepsArrayLoops">Whether a loop that only copies or fills an array is left as the loop alone, and not given the runtime's copy or fill beside it for a long run.</param>
    public static string WriteWithPlaces(EmittedUnit unit, Func<string, long?> placeOf, TextBlock? text = null, bool keepsArrayLoops = false)
    {
        ArgumentNullException.ThrowIfNull(unit);
        ArgumentNullException.ThrowIfNull(placeOf);

        if (unit.File is not { } file)
        {
            return unit.Text;
        }

        // Before the constants are moved, while one is still to be seen
        // for what it is.
        file = ConstantEqualityPass.Apply(WorkingBuffersPass.Apply(file, placeOf));
        if (!keepsArrayLoops)
        {
            file = ArrayLoopPass.Apply(file);
        }

        return CSharpFileWriter.Write(text is null ? file : TextBlockPass.Apply(file, text));
    }

    /// <summary>
    /// Writes the part of the class that keeps the character constants of
    /// its units, for units written to reach them there by
    /// <see cref="WriteWithPlaces"/>: a file of its own, which holds
    /// nothing else.
    /// </summary>
    /// <param name="text">The block, once every unit of the library has been written with it.</param>
    /// <returns>The text of a C# source file.</returns>
    public string EmitTextBlock(TextBlock text)
    {
        ArgumentNullException.ThrowIfNull(text);

        // Literals of so many bytes each, joined when the class is
        // compiled: one literal of the whole would be one line of the
        // file, and one for each constant takes a compiler minutes to
        // join.
        const int LiteralBytes = 4096;

        var whole = text.ToString();
        var literals = Enumerable.Range(0, (whole.Length + LiteralBytes - 1) / LiteralBytes)
            .Select(index => whole.Substring(index * LiteralBytes, Math.Min(LiteralBytes, whole.Length - (index * LiteralBytes))).ToUtf8Literal())
            .ToList();

        var file = new CodeWriter();
        file.Line("// <auto-generated>");
        file.Line("// Written by Fortrania with the code it translated from FORTRAN 77. A change made here is lost when the source is translated again.");
        file.Line("// </auto-generated>");
        file.Blank();
        file.Line("#nullable enable");
        file.Blank();
        file.Line($"namespace {_options.Namespace};");
        file.Blank();
        file.Open($"public unsafe partial class {_options.ClassName}");
        file.Line("// Every character constant of the library, each once, followed by zero bytes up to a multiple");
        file.Line("// of eight. A method reaches one by where it starts, and writes the constant beside the number.");
        file.Line("//");
        file.Line("// They are kept here, and not each where it is used, for speed: a constant written as a literal");
        file.Line("// of its own costs the just-in-time compiler several calls to write in line, and a method with");
        file.Line("// hundreds of them uses up what that compiler allows one method, which leaves it slow and with a");
        file.Line("// large frame. To have each constant written where it is used instead, as the FORTRAN has it,");
        file.Line("// set \"inlineTextConstants\": true in the translation's settings and translate again.");
        file.Line($"private static readonly byte* {TextBlockPass.BlockField} = global::Dracocephalum.Fortrania.Runtime.Fortran.AddrOf(");
        for (var index = 0; index < literals.Count; index++)
        {
            file.Line("    " + literals[index] + (index == literals.Count - 1 ? ");" : " +"));
        }

        file.Close();
        return file.ToString();
    }
}
