namespace Dracocephalum.Fortrania.Plugins;

/// <summary>
/// One C# file of a translation, as <see cref="ITranslationPlugin.BeforeWrite"/>
/// sees it: where it is to be written, what it was made from, and its text,
/// which the plugin may change.
/// </summary>
public sealed class GeneratedFile
{
    // Each file starts so, and a later run removes only a file that does.
    private const string GeneratedLine = "// <auto-generated>";

    private string _text;

    internal GeneratedFile(string project, string source, string path, string? unit, string? sourceFile, string text)
    {
        Project = project;
        Source = source;
        Path = path;
        Unit = unit;
        SourceFile = sourceFile;
        _text = text;
    }

    /// <summary>Gets the name of the project the file is of, its assembly's.</summary>
    public string Project { get; }

    /// <summary>Gets the name of the source the file is of, as its settings give it; its folder of translated files has that name.</summary>
    public string Source { get; }

    /// <summary>Gets the full path the file is written to.</summary>
    public string Path { get; }

    /// <summary>Gets the name of the program unit the file translates; <see langword="null"/> for a file of the library's own, its class or its constants.</summary>
    public string? Unit { get; }

    /// <summary>Gets the full path of the FORTRAN file the unit was read from; <see langword="null"/> where <see cref="Unit"/> is.</summary>
    public string? SourceFile { get; }

    /// <summary>
    /// Gets or sets the file's text. Its first line stays the one that says
    /// it was generated, which is what lets a later run remove it when the
    /// sources no longer give rise to it.
    /// </summary>
    /// <exception cref="ArgumentException">The text does not start with that line.</exception>
    public string Text
    {
        get
        {
            return _text;
        }

        set
        {
            ArgumentNullException.ThrowIfNull(value);
            if (!value.StartsWith(GeneratedLine + "\n", StringComparison.Ordinal) && !value.StartsWith(GeneratedLine + "\r\n", StringComparison.Ordinal))
            {
                throw new ArgumentException($"A generated file's text starts with the line {GeneratedLine}, which says it was generated.", nameof(value));
            }

            _text = value;
        }
    }
}
